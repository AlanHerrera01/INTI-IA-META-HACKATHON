from typing import Protocol
from uuid import UUID

from inti.domain.entities import Observation, VisionAnalysis


class BrowserObservationPort(Protocol):
    async def capture(self, url: str, width: int, height: int) -> Observation: ...
    async def available(self) -> bool: ...


class VisionModelPort(Protocol):
    async def analyze_observation(
        self, observation: Observation, instruction: str
    ) -> VisionAnalysis: ...
    async def status(self) -> dict[str, str | bool | None]: ...


class ObservationRepositoryPort(Protocol):
    async def save(self, observation: Observation) -> None: ...
    async def get(self, id: UUID) -> Observation | None: ...
    async def latest(self, limit: int) -> list[Observation]: ...
    async def available(self) -> bool: ...


class ArtifactStoragePort(Protocol):
    async def write(self, id: UUID, data: bytes) -> None: ...
    async def read(self, id: UUID) -> bytes: ...
    async def delete(self, id: UUID) -> None: ...
